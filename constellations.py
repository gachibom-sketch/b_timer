def sky_degrees(ra, dec):  # "05 55 10.29", "+07 24 25.3" → (적경°, 적위°)
    hours, minutes, seconds = (float(v) for v in ra.split())
    sign = -1 if dec.lstrip()[0] in "-−" else 1
    degrees, arcmin, arcsec = (abs(float(v)) for v in dec.replace("−", "-").split())
    return (hours + minutes / 60 + seconds / 3600) * 15, sign * (degrees + arcmin / 60 + arcsec / 3600)


def flatten(points, center):  # 접평면 투영 — 북쪽이 위, 동쪽이 왼쪽(하늘을 올려다본 모습), 단위는 도
    a0, d0 = (math.radians(v) for v in center)
    flat = []
    for ra, dec in points:
        a, d = math.radians(ra), math.radians(dec)
        cos_c = math.sin(d0) * math.sin(d) + math.cos(d0) * math.cos(d) * math.cos(a - a0)
        x = -math.cos(d) * math.sin(a - a0) / cos_c
        y = (math.cos(d0) * math.sin(d) - math.sin(d0) * math.cos(d) * math.cos(a - a0)) / cos_c
        flat.append((math.degrees(x), math.degrees(y)))
    return flat


def turn(points, angle):  # 시계 방향으로 angle° 돌림
    t = math.radians(angle)
    return [(x * math.cos(t) + y * math.sin(t), -x * math.sin(t) + y * math.cos(t)) for x, y in points]


def build(raw):  # 실제 하늘 좌표 → 정사각형 판 위 자리 (왼쪽 %, 위 %)
    main = [sky_degrees(ra, dec) for _, ra, dec, _, _ in raw["stars"]]
    extra = [sky_degrees(ra, dec) for _, ra, dec, _ in raw["bonus"]]
    center = (sum(p[0] for p in main) / len(main), sum(p[1] for p in main) / len(main))
    flat = turn(flatten(main + extra, center), raw["turn"])
    xs, ys = [p[0] for p in flat[:len(main)]], [p[1] for p in flat[:len(main)]]
    scale = (100 - 2 * raw["margin"]) / max(max(xs) - min(xs), max(ys) - min(ys))  # 긴 쪽을 판에 꽉 채움
    mid_x, mid_y = (max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2
    spots = [(50 + (x - mid_x) * scale, 50 - (y - mid_y) * scale) for x, y in flat]
    star_spots = spots[:len(main)]

    bonus = []
    for (name, *_), spot in zip(raw["bonus"], spots[len(main):]):
        nearest = min(star_spots, key=lambda s: math.dist(s, spot))
        gap = math.dist(nearest, spot)
        if 0 < gap < PAIR:  # 겹쳐 보이는 짝별은 실제 방향 그대로 조금 띄움
            spot = tuple(n + (v - n) * NEAR_STAR / gap for n, v in zip(nearest, spot))
        bonus.append({"name": name, "pos": (round(spot[0], 1), round(spot[1], 1))})

    stars = [
        {
            "name": name,
            "pos": (round(spot[0], 1), round(spot[1], 1)),
            "size": round(max(0.45, min(1.0, 1.15 - 0.15 * mag)), 2),  # 밝을수록 크게 (0등급 1.0 · 5등급 0.45)
            "color": COLORS[kind],
        }
        for (name, _, _, mag, kind), spot in zip(raw["stars"], star_spots)
    ]
    info = {k: raw[k] for k in ("key", "name", "period", "goal", "time", "shape", "lines")}
    return {**info, "recommended": raw["key"] == FIRST, "stars": stars, "bonus": bonus}


